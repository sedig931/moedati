<script>
export default {
  components: {},
  data() {
    return {
      //propreties
    };
  },
  methods: {
    sec1AddHoverAction() {
      const smCards = document.querySelectorAll(".single-samll-card-div");
      smCards.forEach((card, i) => {
        card.addEventListener("mouseover", (e) => {
          if (!e.target.classList.contains("sec1-small-card-btn")) this.sec1SetActiveCard(card.id);
        });
      });
    },
    sec1SetActiveCard(cardid) {
      const card = document.getElementById("sec1-single-card-div-" + cardid[cardid.length - 1]);
      if (!card) return;
      document.querySelectorAll(".sec1-single-card-inner-div").forEach((ele) => {
        ele.querySelector(".sec1-single-card-blur").classList.add("sec1-single-card-set-blur");
      });
      card.querySelector(".sec1-single-card-blur").classList.remove("sec1-single-card-set-blur");

      if (card !== card.parentElement.lastElementChild) {
        card.classList.add("sec1-single-card-inner-div-trans");
        card.parentElement.append(card);
        setTimeout(() => {
          card.classList.remove("sec1-single-card-inner-div-trans");
        }, 100);
      }
    },
    sec1MakeCardsMove() {
      const slider = document.querySelector(".sec1-smalls-cards-div");
      let isDown = false;
      let hasDragged = false;
      let startX;
      let scrollLeft;

      slider.addEventListener("mousedown", (e) => {
        isDown = true;
        hasDragged = false;
        slider.classList.add("active");
        startX = e.pageX - slider.offsetLeft;
        scrollLeft = slider.scrollLeft;
      });
      slider.addEventListener("mouseleave", () => (isDown = false));
      slider.addEventListener("mouseup", () => (isDown = false));
      slider.addEventListener(
        "click",
        (e) => {
          if (hasDragged) {
            e.preventDefault();
            e.stopPropagation();
            hasDragged = false;
          }
        },
        true,
      );
      slider.addEventListener("mousemove", (e) => {
        if (!isDown) return;
        e.preventDefault();
        const x = e.pageX - slider.offsetLeft;
        const walk = (x - startX) * 1; // scroll speed
        if (Math.abs(x - startX) > 5) {
          hasDragged = true;
        }
        slider.scrollLeft = scrollLeft - walk;
      });
    },
  },
  mounted() {
    this.sec1AddHoverAction();
    this.sec1SetActiveCard("0");
    this.sec1MakeCardsMove();
  },
};
</script>
