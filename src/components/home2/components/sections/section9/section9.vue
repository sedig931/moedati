        const contentHeight = content.offsetHeight;
        if (Math.abs(y) >= contentHeight) {
        y = 0;
        }
        content.style.transform = `translateY(${-y}px)`;
        clone.style.transform = `translateY(${-y + -contentHeight}px)`;
        requestAnimationFrame(animate);
